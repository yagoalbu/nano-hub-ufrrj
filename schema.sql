-- NaNo Hub | Esquema inicial para Supabase (PostgreSQL)
-- Execute no SQL Editor do Supabase em um projeto novo ou adapte nomes/colunas
-- caso já existam tabelas em produção. Faça backup antes de alterar tabelas existentes.

create table if not exists public.pesquisadores (
  id bigint generated by default as identity primary key,
  nome text not null,
  email text,
  vinculo text,
  projeto text,
  situacao text default 'Ativo',
  created_at timestamptz default now()
);

create table if not exists public.equipamentos (
  id bigint generated by default as identity primary key,
  nome text not null,
  categoria text,
  localizacao text,
  status text default 'Disponível',
  descricao text,
  created_at timestamptz default now()
);

create table if not exists public.escala_laboratorio (
  id bigint generated by default as identity primary key,
  pesquisador text not null,
  dia_semana text not null,
  turno text not null,
  atividade text,
  created_at timestamptz default now()
);

create table if not exists public.reservas_equipamentos (
  id bigint generated by default as identity primary key,
  pesquisador text not null,
  equipamento text not null,
  data_uso date not null,
  hora_inicio time not null,
  hora_fim time not null,
  observacao text,
  created_at timestamptz default now(),
  constraint horario_valido check (hora_fim > hora_inicio)
);

create table if not exists public.estoque_insumos (
  id bigint generated by default as identity primary key,
  nome text not null,
  categoria text,
  unidade text,
  quantidade_atual numeric(14,3) default 0,
  quantidade_minima numeric(14,3) default 0,
  validade date,
  lote text,
  fornecedor text,
  localizacao text,
  created_at timestamptz default now()
);

create table if not exists public.projetos (
  id bigint generated by default as identity primary key,
  titulo text not null,
  responsavel text,
  financiamento text,
  status text default 'Planejamento',
  data_inicio date,
  resumo text,
  created_at timestamptz default now()
);

create table if not exists public.experimentos (
  id bigint generated by default as identity primary key,
  titulo text not null,
  projeto text,
  responsavel text,
  data_experimento date,
  etapa text,
  materiais text,
  procedimento text,
  resultados text,
  created_at timestamptz default now()
);

create table if not exists public.biblioteca (
  id bigint generated by default as identity primary key,
  titulo text not null,
  tipo text,
  categoria text,
  autor text,
  url text,
  observacoes text,
  created_at timestamptz default now()
);

create table if not exists public.mural_avisos (
  id bigint generated by default as identity primary key,
  autor text,
  categoria text,
  tipo text,
  mensagem text not null,
  created_at timestamptz default now()
);

-- IMPORTANTE:
-- Para um ambiente multiusuário real, configure Supabase Auth e políticas RLS.
-- Não exponha a service_role key no aplicativo. Use a anon key com RLS adequado.
-- Este SQL não ativa RLS automaticamente para evitar bloquear a primeira configuração.
